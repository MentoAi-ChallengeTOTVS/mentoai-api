CREATE TABLE CLIENTE (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(255) NOT NULL,
    SEGMENTO VARCHAR2(100) NOT NULL,
    PORTE VARCHAR2(50) NOT NULL,
    CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    STATUS NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID),
    CONSTRAINT CK_CLIENTE_STATUS CHECK (STATUS IN (0, 1))
);

CREATE TABLE USUARIO (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(255) NOT NULL,
    EMAIL VARCHAR2(255) NOT NULL,
    SENHA VARCHAR2(255) NOT NULL,
    PERFIL VARCHAR2(30) NOT NULL,
    ATIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UQ_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_ATIVO CHECK (ATIVO IN (0, 1)),
    CONSTRAINT CK_USUARIO_PERFIL CHECK (PERFIL IN ('EXECUTIVO_COMERCIAL', 'DIRETOR_COMERCIAL'))
);

CREATE TABLE REUNIAO (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CLIENTE_ID NUMBER(19) NOT NULL,
    USUARIO_ID NUMBER(19) NOT NULL,
    DATA_REUNIAO TIMESTAMP NOT NULL,
    DURACAO_MINUTOS NUMBER(10) NOT NULL,
    CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REUNIAO PRIMARY KEY (ID),
    CONSTRAINT FK_REUNIAO_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID),
    CONSTRAINT FK_REUNIAO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID),
    CONSTRAINT CK_REUNIAO_DURACAO CHECK (DURACAO_MINUTOS >= 0)
);

CREATE INDEX IDX_REUNIAO_CLIENTE_DATA ON REUNIAO (CLIENTE_ID, DATA_REUNIAO);
CREATE INDEX IDX_REUNIAO_USUARIO ON REUNIAO (USUARIO_ID);

CREATE TABLE TRANSCRICAO (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    REUNIAO_ID NUMBER(19) NOT NULL,
    CONTEUDO CLOB NOT NULL,
    NOME_ARQUIVO VARCHAR2(255) NOT NULL,
    FORMATO_ARQUIVO VARCHAR2(50) NOT NULL,
    IDIOMA VARCHAR2(20) NOT NULL,
    CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TRANSCRICAO PRIMARY KEY (ID),
    CONSTRAINT FK_TRANSCRICAO_REUNIAO FOREIGN KEY (REUNIAO_ID) REFERENCES REUNIAO (ID),
    CONSTRAINT UQ_TRANSCRICAO_REUNIAO UNIQUE (REUNIAO_ID)
);

CREATE TABLE ANALISE_IA (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    REUNIAO_ID NUMBER(19) NOT NULL,
    RESUMO_EXECUTIVO CLOB,
    SENTIMENTO_GERAL VARCHAR2(20),
    STATUS_PROCESSAMENTO VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL,
    CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    INICIADO_EM TIMESTAMP,
    FINALIZADO_EM TIMESTAMP,
    MENSAGEM_ERRO CLOB,
    CONSTRAINT PK_ANALISE_IA PRIMARY KEY (ID),
    CONSTRAINT FK_ANALISE_REUNIAO FOREIGN KEY (REUNIAO_ID) REFERENCES REUNIAO (ID),
    CONSTRAINT UQ_ANALISE_REUNIAO UNIQUE (REUNIAO_ID),
    CONSTRAINT CK_ANALISE_SENTIMENTO CHECK (SENTIMENTO_GERAL IS NULL OR SENTIMENTO_GERAL IN ('POSITIVO', 'NEUTRO', 'NEGATIVO')),
    CONSTRAINT CK_ANALISE_STATUS CHECK (STATUS_PROCESSAMENTO IN ('PENDENTE', 'PROCESSANDO', 'PROCESSADA', 'ERRO'))
);

CREATE INDEX IDX_ANALISE_STATUS ON ANALISE_IA (STATUS_PROCESSAMENTO);

CREATE TABLE INSIGHT (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ANALISE_ID NUMBER(19) NOT NULL,
    TIPO VARCHAR2(30) NOT NULL,
    DESCRICAO CLOB NOT NULL,
    SEVERIDADE VARCHAR2(10) NOT NULL,
    CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INSIGHT PRIMARY KEY (ID),
    CONSTRAINT FK_INSIGHT_ANALISE FOREIGN KEY (ANALISE_ID) REFERENCES ANALISE_IA (ID),
    CONSTRAINT CK_INSIGHT_TIPO CHECK (TIPO IN ('RISCO', 'OPORTUNIDADE', 'TENDENCIA', 'ESTRATEGICO')),
    CONSTRAINT CK_INSIGHT_SEVERIDADE CHECK (SEVERIDADE IN ('BAIXA', 'MEDIA', 'ALTA'))
);

CREATE INDEX IDX_INSIGHT_ANALISE ON INSIGHT (ANALISE_ID);

CREATE TABLE SINAL_COMERCIAL (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ANALISE_ID NUMBER(19) NOT NULL,
    TIPO VARCHAR2(30) NOT NULL,
    DESCRICAO CLOB NOT NULL,
    EVIDENCIA CLOB NOT NULL,
    RELEVANCIA VARCHAR2(10) NOT NULL,
    CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SINAL_COMERCIAL PRIMARY KEY (ID),
    CONSTRAINT FK_SINAL_ANALISE FOREIGN KEY (ANALISE_ID) REFERENCES ANALISE_IA (ID),
    CONSTRAINT CK_SINAL_TIPO CHECK (TIPO IN ('NECESSIDADE', 'DOR', 'OBJECAO', 'ORCAMENTO', 'PRAZO', 'MOMENTO_CLIENTE', 'CONCORRENCIA', 'OPORTUNIDADE', 'RISCO_CHURN')),
    CONSTRAINT CK_SINAL_RELEVANCIA CHECK (RELEVANCIA IN ('BAIXA', 'MEDIA', 'ALTA'))
);

CREATE INDEX IDX_SINAL_ANALISE_TIPO ON SINAL_COMERCIAL (ANALISE_ID, TIPO, RELEVANCIA);

CREATE TABLE ALERTA (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    SINAL_COMERCIAL_ID NUMBER(19) NOT NULL,
    PRIORIDADE VARCHAR2(10) NOT NULL,
    MOTIVO CLOB NOT NULL,
    CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ALERTA PRIMARY KEY (ID),
    CONSTRAINT FK_ALERTA_SINAL FOREIGN KEY (SINAL_COMERCIAL_ID) REFERENCES SINAL_COMERCIAL (ID),
    CONSTRAINT UQ_ALERTA_SINAL UNIQUE (SINAL_COMERCIAL_ID),
    CONSTRAINT CK_ALERTA_PRIORIDADE CHECK (PRIORIDADE IN ('BAIXA', 'MEDIA', 'ALTA'))
);

CREATE TABLE ALERTA_USUARIO (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ALERTA_ID NUMBER(19) NOT NULL,
    USUARIO_ID NUMBER(19) NOT NULL,
    LIDO NUMBER(1) DEFAULT 0 NOT NULL,
    LIDO_EM TIMESTAMP,
    CONSTRAINT PK_ALERTA_USUARIO PRIMARY KEY (ID),
    CONSTRAINT FK_ALERTA_USUARIO_ALERTA FOREIGN KEY (ALERTA_ID) REFERENCES ALERTA (ID),
    CONSTRAINT FK_ALERTA_USUARIO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID),
    CONSTRAINT UQ_ALERTA_USUARIO UNIQUE (ALERTA_ID, USUARIO_ID),
    CONSTRAINT CK_ALERTA_USUARIO_LIDO CHECK (LIDO IN (0, 1))
);

CREATE INDEX IDX_ALERTA_USUARIO_LEITURA ON ALERTA_USUARIO (USUARIO_ID, LIDO);

CREATE TABLE CHAT (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID NUMBER(19) NOT NULL,
    TITULO VARCHAR2(255) NOT NULL,
    CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CHAT PRIMARY KEY (ID),
    CONSTRAINT FK_CHAT_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID)
);

CREATE INDEX IDX_CHAT_USUARIO ON CHAT (USUARIO_ID);

CREATE TABLE PERGUNTA_CHAT (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CHAT_ID NUMBER(19) NOT NULL,
    PERGUNTA CLOB NOT NULL,
    RESPOSTA CLOB,
    CRIACAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PERGUNTA_CHAT PRIMARY KEY (ID),
    CONSTRAINT FK_PERGUNTA_CHAT_CHAT FOREIGN KEY (CHAT_ID) REFERENCES CHAT (ID)
);

CREATE INDEX IDX_PERGUNTA_CHAT_CHAT ON PERGUNTA_CHAT (CHAT_ID);
